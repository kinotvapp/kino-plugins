#!/usr/bin/env node
// Kino loads exactly one JavaScript file (the manifest's `entry`), so the modules under src/ are bundled into plugin.js.
// A tiny bundler for this example: it inlines the dependencies of src/index.js (`import { a } from "./x.js"`, named imports
// only) before the entry's own code, with their `export` keywords removed. The entry keeps its exports, so the result is one
// ES module.
//
//   node scripts/build.mjs           writes plugin.js
//   node scripts/build.mjs --check   exits 1 if plugin.js is not what src/ builds to
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const IMPORT = /^import\s*\{[^}]*\}\s*from\s*["'](\.\/[^"']+)["'];?[ \t]*\r?\n/gm;

/** The bundle of [entry] (a path under src/): its relative imports inlined first, in order, once each. */
export function bundle(entry = resolve(root, "src/index.js")) {
  const done = new Set();
  const parts = [];
  const visit = (file, isEntry) => {
    if (done.has(file)) return;
    done.add(file);
    let source = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    source = source.replace(IMPORT, (_, spec) => {
      visit(resolve(dirname(file), spec), false);
      return "";
    });
    if (/^import\s/m.test(source)) throw new Error(`${file}: only \`import { ... } from "./x.js"\` is supported`);
    parts.push(isEntry ? source : source.replace(/^export\s+/gm, ""));
  };
  visit(entry, true);
  return "// Generated by scripts/build.mjs from src/. Do not edit: change src/ and run `node scripts/build.mjs`.\n" + parts.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(root, "plugin.js");
  const text = bundle();
  if (process.argv[2] === "--check") {
    if (readFileSync(out, "utf8").replace(/\r\n/g, "\n") !== text) { console.error("plugin.js is out of date: run node scripts/build.mjs"); process.exitCode = 1; }
  } else {
    writeFileSync(out, text);
  }
}
